#pragma once

/**
 * @file snmp_trap.h
 * @brief SNMPv1 Trap-PDU encoding (RFC 1157 4.1.6) and the device's traps.
 *
 *   Trap-PDU ::= [4] IMPLICIT SEQUENCE {
 *       enterprise OBJECT IDENTIFIER, agent-addr NetworkAddress,
 *       generic-trap INTEGER, specific-trap INTEGER,
 *       time-stamp TimeTicks, variable-bindings VarBindList }
 *
 * Traps sent by the device (see mibs/RF-UPS-MONITOR-MIB.txt):
 *   coldStart              generic 0, at boot once the network is up
 *   authenticationFailure  generic 4, request with a wrong community
 *   mainsPowerLost         enterpriseSpecific (6), specific 1
 *   mainsPowerRestored     enterpriseSpecific (6), specific 2
 * The mains traps carry mainsPowerStatus, mainsPowerChanges and
 * mainsPowerLastChange.
 *
 * Pure C++, unit tested on the host against traps generated by net-snmp.
 */

#include "snmp_mib.h"

/// Standard SNMP trap port
constexpr uint16_t SNMP_TRAP_PORT = 162;

/// Most variable bindings in a trap
constexpr uint8_t SNMP_TRAP_MAX_VARBINDS = 4;

/// generic-trap values (RFC 1157)
enum class SnmpGenericTrap : int32_t {
    ColdStart = 0,
    WarmStart = 1,
    LinkDown = 2,
    LinkUp = 3,
    AuthenticationFailure = 4,
    EgpNeighborLoss = 5,
    EnterpriseSpecific = 6
};

/// specific-trap values for EnterpriseSpecific traps of this device
enum class MainsTrap : int32_t {
    PowerLost = 1,
    PowerRestored = 2
};

/**
 * @brief Fields of one trap
 */
struct SnmpTrap {
    const char* community;
    Oid enterprise;
    uint8_t agentAddr[4];
    SnmpGenericTrap generic;
    int32_t specific;
    uint32_t timestamp;          ///< sysUpTime when the event happened
    uint8_t varbindCount;
    Oid names[SNMP_TRAP_MAX_VARBINDS];
    SnmpValue values[SNMP_TRAP_MAX_VARBINDS];
};

/**
 * @brief Encode a trap message
 * @return Message length, or 0 if it does not fit or the trap is invalid
 */
size_t snmpBuildTrap(const SnmpTrap& trap, uint8_t* out, size_t capacity);

/**
 * @brief Encode coldStart (enterprise = sysObjectID)
 */
size_t snmpBuildColdStartTrap(const char* community, const uint8_t agentAddr[4], uint32_t uptimeTicks,
                              uint8_t* out, size_t capacity);

/**
 * @brief Encode authenticationFailure (enterprise = sysObjectID)
 */
size_t snmpBuildAuthFailureTrap(const char* community, const uint8_t agentAddr[4], uint32_t uptimeTicks,
                                uint8_t* out, size_t capacity);

/**
 * @brief Encode mainsPowerLost or mainsPowerRestored, chosen by state.mainsPresent
 *
 * time-stamp is state.mainsLastChangeTicks, the moment of the change.
 */
size_t snmpBuildMainsTrap(const char* community, const uint8_t agentAddr[4], const SnmpDeviceState& state,
                          uint8_t* out, size_t capacity);

/**
 * @brief Allows at most one event per interval (wrap-around safe)
 *
 * Used so a flood of bad-community requests cannot cause a flood of traps.
 */
class TrapThrottle {
public:
    explicit TrapThrottle(uint32_t intervalMs) : _intervalMs(intervalMs) {}

    /// true if an event may be sent now; records it
    bool allow(uint32_t nowMs);

    /// Events refused since the last allowed one
    uint32_t suppressed() const { return _suppressed; }

private:
    uint32_t _intervalMs;
    bool _sentOnce = false;
    uint32_t _lastMs = 0;
    uint32_t _suppressed = 0;
};
