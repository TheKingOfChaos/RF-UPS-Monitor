"""Embed Bootstrap's CSS in the firmware, gzip-compressed (lib/web_ui/src/bootstrap_css.cpp).

Downloads the pinned version from jsdelivr (or takes a local copy), checks it
against the official Subresource Integrity hash, compresses it
deterministically and writes a C array the web page serves from flash. The
output is committed, so normal builds need no internet.

    python scripts/embed_bootstrap.py [path/to/bootstrap.min.css]
"""

import base64
import gzip
import hashlib
import os
import sys
import urllib.request

VERSION = "5.3.3"
URL = "https://cdn.jsdelivr.net/npm/bootstrap@%s/dist/css/bootstrap.min.css" % VERSION
# Official SRI hash of bootstrap.min.css 5.3.3 (getbootstrap.com)
SRI = "sha384-QWTKZyjpPEjISv5WaRU9OFeRpok6YctnYmDr5pNlyT2bRjXh0JMhjY6hW+ALEwIH"

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "lib", "web_ui", "src", "bootstrap_css.cpp")


def main():
    if len(sys.argv) > 1:
        css = open(sys.argv[1], "rb").read()
    else:
        with urllib.request.urlopen(URL, timeout=30) as r:
            css = r.read()
    actual = "sha384-" + base64.b64encode(hashlib.sha384(css).digest()).decode()
    if actual != SRI:
        sys.exit("integrity check failed: got %s, expected %s" % (actual, SRI))

    # mtime=0 and no file name: the same input always gives the same bytes
    packed = gzip.compress(css, compresslevel=9, mtime=0)
    lines = []
    for i in range(0, len(packed), 20):
        lines.append("    " + ", ".join("0x%02x" % b for b in packed[i:i + 20]) + ",")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by scripts/embed_bootstrap.py - do not edit.\n")
        f.write("// Bootstrap v%s (https://getbootstrap.com/), Copyright 2011-2024 The Bootstrap Authors,\n" % VERSION)
        f.write("// licensed under MIT (https://github.com/twbs/bootstrap/blob/main/LICENSE).\n")
        f.write("// bootstrap.min.css, %d bytes, %s, gzip-compressed to %d bytes.\n\n" % (len(css), SRI, len(packed)))
        f.write('#include "bootstrap_css.h"\n\n')
        f.write("const uint8_t BOOTSTRAP_CSS_GZ[] = {\n%s\n};\n\n" % "\n".join(lines))
        f.write("const size_t BOOTSTRAP_CSS_GZ_LEN = sizeof(BOOTSTRAP_CSS_GZ);\n")
        f.write("const size_t BOOTSTRAP_CSS_LEN = %d;\n" % len(css))
    print("%s: %d bytes of CSS, %d gzipped, integrity OK" % (OUT, len(css), len(packed)))


if __name__ == "__main__":
    main()
